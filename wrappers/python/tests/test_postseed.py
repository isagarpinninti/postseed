import json
import os
import subprocess
import sys
import unittest
from pathlib import Path

import postseed

SCHEMA = """
CREATE TYPE tone AS ENUM ('calm', 'warm');
CREATE TABLE users (id serial PRIMARY KEY, email varchar(80) UNIQUE NOT NULL, tone tone);
CREATE TABLE posts (id bigserial PRIMARY KEY, user_id integer NOT NULL REFERENCES users(id), title text NOT NULL);
"""


def setUpModule():
    if not postseed.ENGINE.exists():
        raise RuntimeError("the bundled engine is missing: run `pnpm build && pnpm bundle:launchers` first")


class GenerateTest(unittest.TestCase):
    def test_returns_a_transactional_script(self):
        sql = postseed.generate(SCHEMA, rows=5)
        self.assertTrue(sql.startswith("-- Generated by Postseed"))
        self.assertIn("BEGIN;", sql)
        self.assertIn("COMMIT;", sql)
        self.assertIn("-- 5 rows for users", sql)
        self.assertIn("-- 5 rows for posts", sql)

    def test_is_deterministic(self):
        a = postseed.generate(SCHEMA, rows=20, seed=7)
        self.assertEqual(a, postseed.generate(SCHEMA, rows=20, seed=7))
        self.assertNotEqual(a, postseed.generate(SCHEMA, rows=20, seed=8))

    def test_options(self):
        sql = postseed.generate(SCHEMA, table_rows={"users": 2, "posts": 9}, null_ratio=0)
        self.assertIn("-- 2 rows for users", sql)
        self.assertIn("-- 9 rows for posts", sql)
        sql = postseed.generate(SCHEMA, rows=3, tables=["users"])
        self.assertNotIn("rows for posts", sql)

    def test_json(self):
        data = json.loads(postseed.generate(SCHEMA, rows=4, format="json"))
        self.assertEqual(len(data["users"]), 4)
        user_ids = {u["id"] for u in data["users"]}
        self.assertTrue(all(p["user_id"] in user_ids for p in data["posts"]))

    def test_rejects_csv_and_reports_engine_errors(self):
        with self.assertRaises(ValueError):
            postseed.generate(SCHEMA, format="csv")
        with self.assertRaises(postseed.PostseedError) as ctx:
            postseed.generate(SCHEMA, tables=["posts"])  # its parent is not selected
        self.assertIn("users", str(ctx.exception))
        with self.assertRaises(postseed.PostseedError):
            postseed.generate("this is not sql")


class NodeTest(unittest.TestCase):
    def test_finds_node(self):
        self.assertTrue(os.path.exists(postseed.find_node()))

    def test_missing_node_has_a_helpful_message(self):
        old = os.environ.get("POSTSEED_NODE")
        os.environ["POSTSEED_NODE"] = "/definitely/not/node"
        try:
            with self.assertRaises(postseed.NodeNotFoundError) as ctx:
                postseed.find_node()
            self.assertIn("Node.js", str(ctx.exception))
        finally:
            if old is None:
                del os.environ["POSTSEED_NODE"]
            else:
                os.environ["POSTSEED_NODE"] = old


class CommandTest(unittest.TestCase):
    def test_version_matches_the_package(self):
        done = postseed.run(["--version"])
        self.assertEqual(done.returncode, 0)
        self.assertEqual(done.stdout.strip(), postseed.__version__)

    def test_python_dash_m(self):
        env = dict(os.environ, PYTHONPATH=str(Path(postseed.__file__).resolve().parent.parent))
        done = subprocess.run([sys.executable, "-m", "postseed", "--version"], capture_output=True, text=True, env=env)
        self.assertEqual(done.returncode, 0)
        self.assertEqual(done.stdout.strip(), postseed.__version__)

    def test_exit_code_is_passed_through(self):
        env = dict(os.environ, PYTHONPATH=str(Path(postseed.__file__).resolve().parent.parent))
        done = subprocess.run([sys.executable, "-m", "postseed", "no-such-command"], capture_output=True, text=True, env=env)
        self.assertEqual(done.returncode, 2)

    def test_missing_node_exits_127(self):
        env = dict(os.environ, POSTSEED_NODE="/definitely/not/node", PYTHONPATH=str(Path(postseed.__file__).resolve().parent.parent))
        done = subprocess.run([sys.executable, "-m", "postseed", "--version"], capture_output=True, text=True, env=env)
        self.assertEqual(done.returncode, 127)
        self.assertIn("Node.js", done.stderr)


if __name__ == "__main__":
    unittest.main()
