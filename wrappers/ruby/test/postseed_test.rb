# frozen_string_literal: true

require "minitest/autorun"
require "json"
require "open3"
require "rbconfig"
$LOAD_PATH.unshift File.expand_path("../lib", __dir__)
require "postseed"

SCHEMA = <<~SQL
  CREATE TYPE tone AS ENUM ('calm', 'warm');
  CREATE TABLE users (id serial PRIMARY KEY, email varchar(80) UNIQUE NOT NULL, tone tone);
  CREATE TABLE posts (id bigserial PRIMARY KEY, user_id integer NOT NULL REFERENCES users(id), title text NOT NULL);
SQL

EXE = File.expand_path("../exe/postseed", __dir__)
LIB = File.expand_path("../lib", __dir__)

class PostseedTest < Minitest::Test
  def setup
    flunk "the bundled engine is missing: run `pnpm build && pnpm bundle:launchers` first" unless File.exist?(Postseed::ENGINE)
  end

  def test_returns_a_transactional_script
    sql = Postseed.generate(SCHEMA, rows: 5)
    assert sql.start_with?("-- Generated by Postseed")
    assert_includes sql, "BEGIN;"
    assert_includes sql, "COMMIT;"
    assert_includes sql, "-- 5 rows for users"
    assert_includes sql, "-- 5 rows for posts"
  end

  def test_is_deterministic
    a = Postseed.generate(SCHEMA, rows: 20, seed: 7)
    assert_equal a, Postseed.generate(SCHEMA, rows: 20, seed: 7)
    refute_equal a, Postseed.generate(SCHEMA, rows: 20, seed: 8)
  end

  def test_options
    sql = Postseed.generate(SCHEMA, table_rows: { "users" => 2, "posts" => 9 }, null_ratio: 0)
    assert_includes sql, "-- 2 rows for users"
    assert_includes sql, "-- 9 rows for posts"
    refute_includes Postseed.generate(SCHEMA, rows: 3, tables: ["users"]), "rows for posts"
  end

  def test_json
    data = JSON.parse(Postseed.generate(SCHEMA, rows: 4, format: "json"))
    assert_equal 4, data["users"].length
    ids = data["users"].map { |u| u["id"] }
    assert(data["posts"].all? { |p| ids.include?(p["user_id"]) })
  end

  def test_rejects_csv_and_reports_engine_errors
    assert_raises(ArgumentError) { Postseed.generate(SCHEMA, format: "csv") }
    error = assert_raises(Postseed::Error) { Postseed.generate(SCHEMA, tables: ["posts"]) }
    assert_includes error.message, "users"
    assert_raises(Postseed::Error) { Postseed.generate("this is not sql") }
  end

  def test_finds_node_and_explains_when_it_cannot
    assert File.exist?(Postseed.find_node)
    old = ENV["POSTSEED_NODE"]
    ENV["POSTSEED_NODE"] = "/definitely/not/node"
    error = assert_raises(Postseed::NodeNotFound) { Postseed.find_node }
    assert_includes error.message, "Node.js"
  ensure
    old.nil? ? ENV.delete("POSTSEED_NODE") : ENV["POSTSEED_NODE"] = old
  end

  def test_executable_passes_output_and_exit_codes_through
    out, _err, status = Open3.capture3(RbConfig.ruby, "-I", LIB, EXE, "--version")
    assert status.success?
    assert_equal Postseed::VERSION, out.strip
    _out, _err, status = Open3.capture3(RbConfig.ruby, "-I", LIB, EXE, "no-such-command")
    assert_equal 2, status.exitstatus
    _out, err, status = Open3.capture3({ "POSTSEED_NODE" => "/definitely/not/node" }, RbConfig.ruby, "-I", LIB, EXE, "--version")
    assert_equal 127, status.exitstatus
    assert_includes err, "Node.js"
  end
end
