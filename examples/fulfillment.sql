-- Postseed example: an order fulfillment schema.
-- Try it: npx postseed generate --schema examples/fulfillment.sql --rows 50 --seed 42

CREATE TYPE order_status AS ENUM ('pending', 'paid', 'packed', 'shipped', 'delivered', 'cancelled');
CREATE TYPE payment_type AS ENUM ('card', 'bank_transfer', 'wallet', 'invoice');

CREATE TABLE users (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email         varchar(120) NOT NULL UNIQUE,
  full_name     text NOT NULL,
  referred_by   bigint REFERENCES users (id) ON DELETE SET NULL,
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE customers (
  id            serial PRIMARY KEY,
  user_id       bigint NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
  company       text,
  phone         varchar(32),
  city          text,
  country       char(2),
  loyalty_points integer NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0)
);

CREATE TABLE products (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sku           varchar(24) NOT NULL UNIQUE,
  title         text NOT NULL,
  description   text,
  price         numeric(10, 2) NOT NULL CHECK (price > 0 AND price <= 2500),
  tags          text[] NOT NULL DEFAULT '{}',
  attributes    jsonb NOT NULL DEFAULT '{}',
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orders (
  id            bigserial PRIMARY KEY,
  customer_id   integer NOT NULL REFERENCES customers (id),
  status        order_status NOT NULL DEFAULT 'pending',
  total         numeric(12, 2) NOT NULL CHECK (total >= 0),
  placed_at     timestamptz NOT NULL,
  notes         text
);

CREATE TABLE order_items (
  order_id      bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id    uuid NOT NULL REFERENCES products (id),
  quantity      integer NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  unit_price    numeric(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE payments (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      bigint NOT NULL REFERENCES orders (id),
  kind          payment_type NOT NULL,
  amount        numeric(12, 2) NOT NULL CHECK (amount > 0),
  paid_at       timestamptz,
  reference     text UNIQUE
);

CREATE TABLE shipments (
  id            bigserial PRIMARY KEY,
  order_id      bigint NOT NULL UNIQUE REFERENCES orders (id),
  carrier       text NOT NULL,
  tracking_code varchar(40) NOT NULL UNIQUE,
  shipped_at    timestamptz,
  delivered_at  timestamptz,
  ip_address    inet
);

CREATE TABLE inventory (
  product_id    uuid NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  warehouse     text NOT NULL,
  on_hand       integer NOT NULL CHECK (on_hand >= 0),
  reorder_level integer NOT NULL DEFAULT 10,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (product_id, warehouse)
);
