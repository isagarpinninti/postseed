import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { connect } from "@postseed/pg";
import { run } from "../src/run";
import type { Io } from "../src/io";
import { HAS_PG, startPostgres, type TestServer } from "../../pg/test/pgserver";

const schemaPath = new URL("../../../examples/fulfillment.sql", import.meta.url).pathname;

interface Captured {
  io: Io;
  out: () => string;
  err: () => string;
}

function capture(cwd: string, opts: { interactive?: boolean; answers?: string[]; env?: Record<string, string> } = {}): Captured {
  let out = "";
  let err = "";
  const answers = [...(opts.answers ?? [])];
  return {
    io: {
      out: (t) => void (out += t),
      err: (t) => void (err += t),
      env: opts.env ?? {},
      cwd,
      interactive: opts.interactive ?? false,
      color: false,
      prompt: async (q) => {
        err += q;
        return answers.shift() ?? "";
      },
      readStdin: async () => "",
    },
    out: () => out,
    err: () => err,
  };
}

let dir = "";
beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), "postseed-cli-"));
});

describe("generate", () => {
  it("prints deterministic SQL for a schema file", async () => {
    const a = capture(dir);
    const b = capture(dir);
    expect(await run(["generate", "--schema", schemaPath, "--rows", "5", "--seed", "42"], a.io)).toBe(0);
    expect(await run(["generate", "--schema", schemaPath, "--rows", "5", "--seed", "42"], b.io)).toBe(0);
    expect(a.out()).toBe(b.out());
    expect(a.out()).toContain("BEGIN;");
    expect(a.out()).toContain("-- Generated by Postseed · seed=42");
    expect(a.err()).toContain("40 rows across 8 tables");
  });

  it("writes to --out and honours --tables, --table-rows and --null-ratio", async () => {
    const out = join(dir, "seed.sql");
    const c = capture(dir);
    expect(await run(["generate", "--schema", schemaPath, "--tables", "users,customers", "--table-rows", "users=3,customers=3", "--null-ratio", "0", "--out", out], c.io)).toBe(0);
    const sql = await readFile(out, "utf8");
    expect(sql).toContain("-- 3 rows for users");
    expect(sql).toContain("-- 3 rows for customers");
    expect(sql).not.toContain("for orders");
    // Only the root of the self-referencing users.referred_by is NULL; nullRatio 0 removes every other NULL.
    expect((sql.match(/NULL/g) ?? []).length).toBeLessThanOrEqual(1);
  });

  it("writes json and csv", async () => {
    const j = capture(dir);
    expect(await run(["generate", "--schema", schemaPath, "--rows", "2", "--format", "json", "--tables", "users"], j.io)).toBe(0);
    expect(JSON.parse(j.out()).users).toHaveLength(2);
    const csvDir = join(dir, "csv");
    expect(await run(["generate", "--schema", schemaPath, "--rows", "4", "--format", "csv", "--tables", "users", "--out", csvDir], capture(dir).io)).toBe(0);
    expect((await readFile(join(csvDir, "users.csv"), "utf8")).split("\n")[0]).toBe("id,email,full_name,referred_by,is_active,created_at");
  });

  it("reads postseed.config.ts (overrides and rows) and lets flags win", async () => {
    const proj = await mkdtemp(join(tmpdir(), "postseed-cfg-"));
    await writeFile(join(proj, "postseed.config.ts"), `export default { rows: 3, nullRatio: 0, overrides: { "users.email": { template: "user{n}@example.com" } } };`);
    const a = capture(proj);
    expect(await run(["generate", "--schema", schemaPath, "--tables", "users"], a.io)).toBe(0);
    expect(a.out()).toContain("'user1@example.com'");
    expect(a.out()).toContain("-- 3 rows for users");
    const b = capture(proj);
    expect(await run(["generate", "--schema", schemaPath, "--tables", "users", "--rows", "1"], b.io)).toBe(0);
    expect(b.out()).toContain("-- 1 rows for users");
  });

  it("explains usage mistakes with exit code 2", async () => {
    const c = capture(dir);
    expect(await run(["generate", "--schema", schemaPath, "--format", "csv"], c.io)).toBe(2);
    expect(c.err()).toContain("--out <directory>");
    expect(await run(["generate", "--schema", schemaPath, "--rows", "abc"], capture(dir).io)).toBe(2);
    expect(await run(["generate", "--nope"], capture(dir).io)).toBe(2);
    expect(await run(["generate"], capture(dir).io)).toBe(2);
    expect(await run(["wat"], capture(dir).io)).toBe(2);
    const bad = await mkdtemp(join(tmpdir(), "postseed-badcfg-"));
    await writeFile(join(bad, "postseed.config.ts"), `export default { rowz: 3 };`);
    const e = capture(bad);
    expect(await run(["generate", "--schema", schemaPath], e.io)).toBe(2);
    expect(e.err()).toContain('unknown option "rowz"');
  });

  it("fails with exit 1 and a clear message when a parent table is not selected", async () => {
    const c = capture(dir);
    expect(await run(["generate", "--schema", schemaPath, "--tables", "orders"], c.io)).toBe(1);
    expect(c.err()).toContain("Select customers");
  });

  it("prints help and version", async () => {
    const h = capture(dir);
    expect(await run(["--help"], h.io)).toBe(0);
    expect(h.out()).toContain("postseed generate");
    expect(await run(["generate", "--help"], h.io)).toBe(0);
    const v = capture(dir);
    expect(await run(["--version"], v.io)).toBe(0);
    expect(v.out().trim()).toBe("0.1.0");
  });

  it("init writes a config and refuses to overwrite it", async () => {
    const p = await mkdtemp(join(tmpdir(), "postseed-init-"));
    expect(await run(["init"], capture(p).io)).toBe(0);
    expect(await readFile(join(p, "postseed.config.ts"), "utf8")).toContain("defineConfig");
    expect(await run(["init"], capture(p).io)).toBe(1);
    expect(await run(["init", "--force"], capture(p).io)).toBe(0);
  });
});

describe.skipIf(!HAS_PG)("insert and introspect against Postgres", () => {
  let server: TestServer;
  let url = "";
  beforeAll(async () => {
    server = await startPostgres();
    url = await server.createDatabase("cli_test");
    const c = await connect(url);
    await c.query(await readFile(schemaPath, "utf8"));
    await c.end();
  }, 90_000);
  afterAll(async () => {
    await server?.stop();
  });

  const count = async (table: string): Promise<number> => {
    const c = await connect(url);
    try {
      return Number((await c.query(`SELECT count(*) AS n FROM ${table}`)).rows[0].n);
    } finally {
      await c.end();
    }
  };

  it("introspects", async () => {
    const c = capture(dir);
    expect(await run(["introspect", "--url", url], c.io)).toBe(0);
    expect(c.out()).toContain("8 tables, 2 enums");
    expect(c.out()).toContain("order_items");
  });

  it("requires confirmation, then dry-runs, then inserts", async () => {
    const noYes = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "20"], noYes.io)).toBe(2);
    expect(noYes.err()).toContain("--yes");

    const dry = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "20", "--dry-run"], dry.io)).toBe(0);
    expect(dry.err()).toContain("Dry run passed");
    expect(await count("users")).toBe(0);

    const real = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "20", "--yes"], real.io)).toBe(0);
    expect(real.err()).toContain("Transaction committed");
    expect(await count("users")).toBe(20);
    expect(await count("order_items")).toBe(20);
  });

  it("appends a second batch that continues the ids", async () => {
    const c = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "10", "--seed", "7", "--yes"], c.io)).toBe(0);
    expect(await count("orders")).toBe(30);
  });

  it("refuses --truncate without the database name, and --yes is not enough", async () => {
    const c = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "5", "--truncate", "--yes"], c.io)).toBe(2);
    expect(c.err()).toContain("--confirm-database cli_test");
    expect(await count("users")).toBe(30);
    const typed = capture(dir, { interactive: true, answers: ["wrong"] });
    expect(await run(["insert", "--url", url, "--rows", "5", "--truncate"], typed.io)).toBe(1);
    expect(await count("users")).toBe(30);
  });

  it("truncates when the name is confirmed", async () => {
    const c = capture(dir);
    expect(await run(["insert", "--url", url, "--rows", "5", "--truncate", "--confirm-database", "cli_test"], c.io)).toBe(0);
    expect(c.err()).toContain("CASCADE");
    expect(await count("users")).toBe(5);
  });

  it("exits 3 when a dry run finds a violation, and 1 for a failed real insert", async () => {
    const proj = await mkdtemp(join(tmpdir(), "postseed-bad-"));
    await writeFile(join(proj, "postseed.config.ts"), `export default { rows: 5, overrides: { "products.price": { value: -1 } } };`);
    const dry = capture(proj);
    expect(await run(["insert", "--url", url, "--dry-run", "--tables", "products"], dry.io)).toBe(3);
    expect(dry.err()).toContain("products_price_check");
    const real = capture(proj);
    expect(await run(["insert", "--url", url, "--yes", "--tables", "products"], real.io)).toBe(1);
    expect(real.err()).toContain("no rows were committed");
  });

  it("never prints the password", async () => {
    const withPw = (() => { const u = new URL(url); u.password = "sup3rsecret"; return u.toString(); })();
    const c = capture(dir);
    await run(["insert", "--url", withPw, "--rows", "1", "--dry-run"], c.io);
    expect(c.err() + c.out()).not.toContain("sup3rsecret");
  });
});
