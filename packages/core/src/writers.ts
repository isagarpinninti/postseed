import type { GenEvent } from "./engine";
import { tableKey, type Column, type Table } from "./ir";
import { VERSION } from "./engine";
import { csvCell, jsonValue, qualified, quoteIdent, quoteString, sqlLiteral, type Value } from "./value";

export interface SqlWriterOptions {
  /** Rows per INSERT statement (default 500). */
  batchSize?: number;
  /** Wrap in BEGIN/COMMIT (default true). */
  transaction?: boolean;
}

const SEPARATOR = "·";

/** Streams a SQL script; never builds the whole output in memory. */
export function* writeSql(events: Iterable<GenEvent>, options: SqlWriterOptions = {}): Generator<string> {
  const batch = Math.max(1, options.batchSize ?? 500);
  const transaction = options.transaction !== false;
  for (const e of events) {
    switch (e.type) {
      case "begin": {
        const name = e.name ? ` ${SEPARATOR} ${e.name.replace(/[\r\n]+/g, " ")}` : "";
        yield `-- Generated by Postseed ${SEPARATOR} seed=${e.seed}${name}\n`;
        yield `-- Postseed ${VERSION}: the same schema, seed and options always produce exactly this script.\n`;
        for (const w of e.warnings) yield `-- warning: ${w.replace(/[\r\n]+/g, " ")}\n`;
        if (transaction) yield "BEGIN;\n";
        if (e.deferConstraints) yield "SET CONSTRAINTS ALL DEFERRED;\n";
        break;
      }
      case "table": {
        const notes = e.fkNotes.length > 0 ? `  (${e.fkNotes.join("; ")})` : "";
        const shown = e.shown !== undefined && e.shown < e.rows ? ` (showing the first ${e.shown.toLocaleString("en-US")})` : "";
        yield `\n-- ${e.rows} rows for ${e.table.name}${notes}${shown}\n`;
        break;
      }
      case "rows": {
        const target = qualified(e.table.schema, e.table.name);
        const cols = e.columns.map((c) => quoteIdent(c.name)).join(", ");
        const overriding = e.columns.some((c) => c.identity === "always") ? " OVERRIDING SYSTEM VALUE" : "";
        for (let at = 0; at < e.rows.length; at += batch) {
          const slice = e.rows.slice(at, at + batch);
          const lines = slice.map((r) => `  (${r.map((v, k) => sqlLiteral(v, e.columns[k] as Column)).join(", ")})`);
          yield `INSERT INTO ${target} (${cols})${overriding} VALUES\n${lines.join(",\n")};\n`;
        }
        break;
      }
      case "table-end": {
        for (const s of e.sequences) {
          const tbl = quoteString(qualified(e.table.schema, e.table.name));
          yield `SELECT setval(pg_get_serial_sequence(${tbl}, ${quoteString(s.column)}), ${s.value}, true);\n`;
        }
        break;
      }
      case "updates": {
        yield `\n-- fill in ${e.setColumns.map((c) => c.name).join(", ")} on ${e.table.name} now that every parent row exists\n`;
        const target = qualified(e.table.schema, e.table.name);
        for (const r of e.rows) {
          const set = e.setColumns.map((c, k) => `${quoteIdent(c.name)} = ${sqlLiteral(r.set[k] as Value, c)}`).join(", ");
          const where = e.pkColumns.map((c, k) => `${quoteIdent(c.name)} = ${sqlLiteral(r.pk[k] as Value, c)}`).join(" AND ");
          yield `UPDATE ${target} SET ${set} WHERE ${where};\n`;
        }
        break;
      }
      case "end":
        if (transaction) yield "\nCOMMIT;\n";
        break;
    }
  }
}

/* ─────────────── JSON and CSV need final values, so cycle UPDATEs are applied first ─────────────── */

interface Buffered {
  table: Table;
  columns: Column[];
  rows: Value[][];
}

/**
 * Re-emits events with UPDATEs folded into the rows they change. Without cycles it streams;
 * with cycles it holds the affected output in memory (an UPDATE needs the whole table first).
 */
export function* foldUpdates(events: Iterable<GenEvent>): Generator<GenEvent> {
  const iterator = events[Symbol.iterator]();
  const first = iterator.next();
  if (first.done) return;
  const begin = first.value;
  yield begin;
  if (begin.type !== "begin" || !begin.hasUpdates) {
    for (let r = iterator.next(); !r.done; r = iterator.next()) yield r.value;
    return;
  }
  const held = new Map<string, Buffered>();
  const order: string[] = [];
  const meta = new Map<string, Extract<GenEvent, { type: "table" }>>();
  const tail: GenEvent[] = [];
  for (let r = iterator.next(); !r.done; r = iterator.next()) {
    const e = r.value;
    if (e.type === "table") {
      meta.set(e.key, e);
      held.set(e.key, { table: e.table, columns: e.columns, rows: [] });
      order.push(e.key);
    } else if (e.type === "rows") held.get(e.key)?.rows.push(...e.rows);
    else if (e.type === "updates") {
      const b = held.get(e.key);
      if (!b) continue;
      const pkIdx = e.pkColumns.map((c) => b.columns.findIndex((x) => x.name === c.name));
      const setIdx = e.setColumns.map((c) => b.columns.findIndex((x) => x.name === c.name));
      const byPk = new Map<string, Value[]>();
      for (const row of b.rows) byPk.set(JSON.stringify(pkIdx.map((x) => row[x])), row);
      for (const u of e.rows) {
        const row = byPk.get(JSON.stringify(u.pk));
        if (row) setIdx.forEach((x, k) => (row[x] = u.set[k] as Value));
      }
    } else if (e.type === "end") tail.push(e);
  }
  for (const key of order) {
    const b = held.get(key) as Buffered;
    const m = meta.get(key) as Extract<GenEvent, { type: "table" }>;
    yield m;
    yield { type: "rows", key, table: b.table, columns: b.columns, rows: b.rows, offset: 0 };
  }
  for (const e of tail) yield e;
}

export interface JsonWriterOptions {
  /** `object`: one `{ table: rows[] }` document. `ndjson`: one `{ table, row }` per line. */
  mode?: "object" | "ndjson";
  pretty?: boolean;
}

function rowObject(columns: readonly Column[], row: readonly Value[]): Record<string, Value> {
  const o: Record<string, Value> = {};
  columns.forEach((c, k) => {
    o[c.name] = jsonValue(row[k] as Value, c);
  });
  return o;
}

export function* writeJson(events: Iterable<GenEvent>, options: JsonWriterOptions = {}): Generator<string> {
  const mode = options.mode ?? "object";
  let firstTable = true;
  let firstRow = true;
  for (const e of foldUpdates(events)) {
    if (e.type === "begin" && mode === "object") yield "{";
    else if (e.type === "table" && mode === "object") {
      yield `${firstTable ? "\n" : "\n  ],\n"}  ${JSON.stringify(e.table.name)}: [`;
      firstTable = false;
      firstRow = true;
    } else if (e.type === "rows") {
      for (const r of e.rows) {
        const obj = rowObject(e.columns, r);
        if (mode === "ndjson") yield `${JSON.stringify({ table: e.table.name, row: obj })}\n`;
        else {
          yield `${firstRow ? "\n" : ",\n"}    ${JSON.stringify(obj)}`;
          firstRow = false;
        }
      }
    } else if (e.type === "end" && mode === "object") yield firstTable ? "}\n" : "\n  ]\n}\n";
  }
}

export interface CsvChunk {
  /** File name for this table, e.g. `users.csv`. */
  file: string;
  text: string;
}

export const csvFileName = (t: { schema: string; name: string }): string =>
  t.schema === "public" ? `${t.name}.csv` : `${t.schema}.${t.name}.csv`;

/** One CSV per table (header first), in the dialect `COPY ... CSV HEADER` reads. */
export function* writeCsv(events: Iterable<GenEvent>): Generator<CsvChunk> {
  for (const e of foldUpdates(events)) {
    if (e.type === "table") {
      yield { file: csvFileName(e.table), text: `${e.columns.map((c) => csvCell(c.name)).join(",")}\n` };
    } else if (e.type === "rows") {
      yield { file: csvFileName(e.table), text: e.rows.map((r) => `${r.map((v) => csvCell(v)).join(",")}\n`).join("") };
    }
  }
}

export { tableKey };

/** Keeps only the first `limit` rows of every table (a preview). Row counts in the table events are left as they are. */
export function* previewEvents(events: Iterable<GenEvent>, limit: number): Generator<GenEvent> {
  const taken = new Map<string, number>();
  for (const e of events) {
    if (e.type === "table") yield { ...e, shown: Math.min(e.rows, limit) };
    else if (e.type === "rows") {
      const t = taken.get(e.key) ?? 0;
      if (t >= limit) continue;
      const rows = e.rows.slice(0, limit - t);
      taken.set(e.key, t + rows.length);
      yield { ...e, rows };
    } else if (e.type === "updates") yield { ...e, rows: e.rows.slice(0, limit) };
    else yield e;
  }
}

/** One text rendering for any format; CSV files are separated by `# name.csv` lines. Used for previews. */
export function* renderText(events: Iterable<GenEvent>, format: "sql" | "json" | "csv"): Generator<string> {
  if (format === "sql") yield* writeSql(events);
  else if (format === "json") yield* writeJson(events);
  else {
    let current = "";
    for (const c of writeCsv(events)) {
      if (c.file !== current) {
        current = c.file;
        yield `# ${c.file}\n`;
      }
      yield c.text;
    }
  }
}
