// A "clean machine" check of what would be published: pack the three packages, install them into an empty
// folder (as `npm i postseed` would), then run the real commands, and start Studio and talk to it.
import { execFileSync, spawn } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const work = mkdtempSync(join(tmpdir(), "postseed-smoke-"));
const packs = join(work, "packs");
const app = join(work, "app");
mkdirSync(packs);
mkdirSync(app);

let failures = 0;
const check = (ok, message) => {
  console.log(`${ok ? "✔" : "✖"} ${message}`);
  if (!ok) failures++;
};
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });

for (const name of ["@postseed/core", "@postseed/pg", "postseed"]) run("pnpm", ["--filter", name, "pack", "--pack-destination", packs], { cwd: root });
const tarballs = Object.fromEntries(readdirSync(packs).map((f) => [f.startsWith("postseed-core") ? "@postseed/core" : f.startsWith("postseed-pg") ? "@postseed/pg" : "postseed", join(packs, f)]));
const dep = (k) => `file:${tarballs[k]}`;
writeFileSync(
  join(app, "package.json"),
  JSON.stringify({ name: "smoke", private: true, dependencies: { postseed: dep("postseed") }, overrides: { "@postseed/core": dep("@postseed/core"), "@postseed/pg": dep("@postseed/pg") } }),
);
run("npm", ["install", "--no-audit", "--no-fund", "--loglevel=error"], { cwd: app });
const bin = join(app, "node_modules", ".bin", "postseed");

check(run(bin, ["--version"], { cwd: app }).trim() === JSON.parse(readFileSync(join(root, "packages/postseed/package.json"), "utf8")).version, "postseed --version matches the package");
check(readdirSync(join(app, "node_modules/postseed/studio-dist")).includes("index.html"), "the published package contains the built Studio");

const schema = join(root, "examples/fulfillment.sql");
const gen = () => run(bin, ["generate", "--schema", schema, "--rows", "20", "--seed", "42"], { cwd: app });
const a = gen();
check(a.startsWith("-- Generated by Postseed") && a.includes("BEGIN;") && a.includes("COMMIT;"), "generate writes a transactional SQL script");
check(a === gen(), "seed 42 twice gives identical SQL");

// Studio: start, trade the link token for a cookie, load the app, call the API.
const child = spawn(bin, ["--no-open", "--port", "0"], { cwd: app, stdio: ["ignore", "pipe", "pipe"] });
const url = await new Promise((resolveUrl, reject) => {
  let out = "";
  const timer = setTimeout(() => reject(new Error(`Studio did not start:\n${out}`)), 15000);
  const onData = (d) => {
    out += d.toString();
    const m = /(http:\/\/127\.0\.0\.1:\d+\/\?t=[\w-]+)/.exec(out);
    if (m) {
      clearTimeout(timer);
      resolveUrl(m[1]);
    }
  };
  child.stdout.on("data", onData);
  child.stderr.on("data", onData);
});
try {
  const origin = new URL(url).origin;
  const token = new URL(url).searchParams.get("t");
  check((await fetch(`${origin}/`)).status === 403, "Studio refuses a request without the token");
  const first = await fetch(url, { redirect: "manual" });
  const cookie = (first.headers.get("set-cookie") ?? "").split(";")[0];
  const page = await fetch(`${origin}/`, { headers: { cookie } });
  const html = await page.text();
  check(first.status === 302 && page.status === 200 && html.includes("Postseed Studio") && html.includes('name="postseed-token"'), "Studio serves the app after the token handshake");
  const health = await fetch(`${origin}/api/health`, { headers: { "x-postseed-token": token ?? "" } });
  check(health.status === 200 && (await health.json()).ok === true, "the API answers with the token");
  const bad = await fetch(`${origin}/api/health`, { headers: { "x-postseed-token": token ?? "", origin: "https://evil.example" } });
  check(bad.status === 403, "a cross-origin request is refused");
} finally {
  child.kill("SIGTERM");
}

console.log(failures === 0 ? "\nsmoke test passed" : `\nsmoke test FAILED (${failures})`);
process.exit(failures === 0 ? 0 : 1);
